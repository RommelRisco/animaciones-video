function star(cx, cy, R, r, n = 5) {
  let d = '';
  for (let i = 0; i < n * 2; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / n, rr = i % 2 ? r : R;
    d += `${i ? 'L' : 'M'}${(cx + Math.cos(a) * rr).toFixed(1)},${(cy + Math.sin(a) * rr).toFixed(1)} `;
  }
  return d + 'Z';
}
function gear(cx, cy, R, r, n = 8) {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2, w = Math.PI / n * 0.55;
    const pts = [[a - w * 1.25, r], [a - w * 0.7, R], [a + w * 0.7, R], [a + w * 1.25, r]];
    pts.forEach(([ang, rad], j) => { d += `${i === 0 && j === 0 ? 'M' : 'L'}${(cx + Math.cos(ang) * rad).toFixed(1)},${(cy + Math.sin(ang) * rad).toFixed(1)} `; });
  }
  return d + 'Z';
}
const circ = (cx, cy, r) => `M${cx - r},${cy} A${r},${r} 0 1,0 ${cx + r},${cy} A${r},${r} 0 1,0 ${cx - r},${cy}`;

